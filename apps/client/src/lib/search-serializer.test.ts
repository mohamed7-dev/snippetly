import { defaultStringifySearch } from '@tanstack/react-router';
import { currentUserOutboxListDto } from '@snippetly/common/dto';
import { describe, expect, it } from 'vitest';
import { parseSearch, stringifySearch } from './search-serializer';

describe('search serialization', () => {
    it('round-trips readable nested filters, operators, and sorts for tabs', () => {
        const search = {
            tab: 'sent',
            sent: {
                sort: { addresseeFirstName: 'ASC', addresseeLastName: 'DESC' },
                filter: {
                    status: { equals: 'pending' },
                    _or: [{ addresseeFirstName: { contains: 'Alex' } }, { addresseeLastName: { contains: 'Lee' } }],
                },
                filterOperator: 'OR',
            },
        };

        const serialized = stringifySearch(search);

        expect(serialized).toContain('sent.sort.addresseeFirstName=ASC');
        expect(serialized).toContain('sent.filter.status.equals=pending');
        expect(serialized).toContain('sent.filterOperator=OR');
        expect(parseSearch(serialized)).toEqual(search);
    });

    it('round-trips nested search state on pages without tabs', () => {
        const search = {
            filter: { status: { equals: 'pending' } },
            sort: { createdAt: 'DESC' },
            filterOperator: 'AND',
        };

        expect(parseSearch(stringifySearch(search))).toEqual(search);
    });

    it('round-trips sort values used in outbox filters', () => {
        const search = {
            sent: {
                sort: { addresseeFirstName: 'ASC' },
                filterOperator: 'AND',
            },
        };
        const serialized = stringifySearch(search);

        expect(serialized).toContain('sent.sort.addresseeFirstName=ASC');
        expect(parseSearch(serialized)).toEqual(search);
        expect(
            currentUserOutboxListDto.input.safeParse({ sort: parseSearch(serialized).sent.sort }).success,
        ).toBe(true);
    });

    it('continues to parse existing nested-format URLs', () => {
        const search = {
            tab: 'sent',
            sent: {
                sort: { addresseeFirstName: 'ASC' },
                filter: { status: { equals: 'accepted' } },
                filterOperator: 'AND',
            },
        };
        const previousFormat = defaultStringifySearch(search);

        expect(parseSearch(previousFormat)).toEqual(search);
    });

    it('parses URLs generated by the previous requests-only serializer', () => {
        expect(
            parseSearch(
                '?tab=sent&requests.sent.sort.addresseeFirstName=ASC&requests.sent.filterOperator=OR',
            ),
        ).toEqual({
            tab: 'sent',
            sent: {
                sort: { addresseeFirstName: 'ASC' },
                filterOperator: 'OR',
            },
        });
    });
});
